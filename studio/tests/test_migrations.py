"""Testes das migracoes Alembic do banco de metadados.

O ``alembic/env.py`` le a URL a partir de ``STUDIO_DATABASE_URL`` (via
``get_settings()``), portanto o teste injeta a variavel de ambiente e limpa o cache de
configuracao antes e depois de cada caso.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config as AlembicConfig
from sqlalchemy import inspect

from app.core.config import get_settings, reset_settings_cache
from app.db.session import build_engine
from app.main import run_migrations

TABELAS_ESPERADAS = {
    "users",
    "projects",
    "project_access",
    "datasources",
    "datasource_objects",
    "endpoints",
    "endpoint_versions",
    "api_keys",
    "request_logs",
    "audit_logs",
    "refresh_tokens",
    "settings",
}


@pytest.fixture()
def banco_temporario(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> str:
    """Aponta ``STUDIO_DATABASE_URL`` para um SQLite temporario e limpa o cache."""
    url = f"sqlite:///{(tmp_path / 'meta.db').as_posix()}"
    monkeypatch.setenv("STUDIO_DATABASE_URL", url)
    reset_settings_cache()
    try:
        yield url
    finally:
        reset_settings_cache()


def _config() -> AlembicConfig:
    """Configuracao Alembic equivalente a usada em ``app.main.run_migrations``."""
    settings = get_settings()
    config = AlembicConfig(str(settings.base_dir / "alembic.ini"))
    config.set_main_option("script_location", str(settings.base_dir / "alembic"))
    config.set_main_option("sqlalchemy.url", settings.database_url)
    return config


def test_upgrade_head_cria_schema_completo(banco_temporario: str):
    command.upgrade(_config(), "head")

    engine = build_engine(get_settings().database_url, pool_pre_ping=False)
    try:
        tabelas = set(inspect(engine).get_table_names())
    finally:
        engine.dispose()

    assert TABELAS_ESPERADAS <= tabelas


def test_check_nao_detecta_divergencias(banco_temporario: str):
    config = _config()
    command.upgrade(config, "head")
    # Nao deve levantar AutogenerateDiffsDetected.
    command.check(config)


def test_run_migrations_aplica_head(banco_temporario: str):
    run_migrations(get_settings())

    engine = build_engine(get_settings().database_url, pool_pre_ping=False)
    try:
        tabelas = set(inspect(engine).get_table_names())
    finally:
        engine.dispose()

    assert "endpoint_versions" in tabelas
    assert "api_keys" in tabelas
